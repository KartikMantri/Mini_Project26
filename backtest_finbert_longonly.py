"""
Phase 5 variant — long-only on the FinBERT score
=================================================
No shorting: 100% of capital in the calls the model likes most. Same timing and rules as
backtest_finbert.py (the main, market-neutral result, which this script does not change):

  SIGNAL   at each call, BUY if its score is in the top LONG_PCT of the past 365 days' scores
  TIMING   enter at the close of day +2, exit at the close of day +60
  SIZING   equal weight across all open positions, 100% of capital
  IDLE     if no position is open, the money sits in the S&P 500
  COSTS    10 bps per buy or sell on the weight traded (no borrow fee: nothing is shorted)

Results are RAW returns compared with holding the S&P 500, plus alpha (return beyond the
strategy's market exposure). Benchmarks include "buy every call": the same timing and equal
weights with no score, which shows how much comes from the score rather than from owning this
universe of large companies after their calls.

Caveat: stock prices are dividend-adjusted, but ^GSPC is the price index without dividends, so
the comparison with the S&P 500 flatters the strategy by roughly the index's dividend yield.
"Buy every call" has the same dividend treatment, so the score's contribution is measured fairly
against it.

Usage:
    python backtest_finbert_longonly.py                 # top 15%
    python backtest_finbert_longonly.py --long-pct 0.20
"""

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from backtest_finbert import (BAD_PRICE_TICKERS, COST_BPS, COST_GRID, NW_LAGS, PERIOD_NAME,
                              PERIODS, PRED_CSV, VELU_CSV, Market, assign_sides, build_trades,
                              by_year, daily_portfolio, in_years, metrics, net_returns, pct, stars)
from backtest_finbert_2to1 import HEAD, row, two_to_one, vs_market
from event_returns import load_prices


def long_only(day, cost_bps=COST_BPS):
    """Raw daily return of 100% in the open longs, after costs."""
    return day["long_ret"] - cost_bps / 1e4 * day["turn_long"]


def live_days(calls, col, name, m, top, bottom=0.0):
    trades, paths = build_trades(assign_sides(calls, col, top, bottom), m, name)
    day = daily_portfolio(paths, m)
    held = day["n_long"] > 0
    live = (day.index >= held.idxmax()) & (day.index <= pd.Timestamp(trades["entry_date"].max()))
    return day[live]


def write_results(series, day_ours, long_pct, out_md, chart_png):
    sp = series["sp500"]
    lp = f"{long_pct:.0%}"
    L = [f"# Phase 5 variant — Long-only, top {lp} of scores", "",
         "Generated by [`backtest_finbert_longonly.py`](../backtest_finbert_longonly.py). The main "
         "market-neutral result is unchanged: [`Phase5_finbert_results.md`](Phase5_finbert_results.md).",
         "",
         f"**Rule:** at each call, BUY if its score is in the top {lp} of the previous 365 days' "
         "scores; enter at day +2's close, exit at day +60's. 100% of capital, equal weight across "
         "open positions, no shorting; if nothing is open the money sits in the S&P 500.  ",
         f"**Costs:** {COST_BPS} bps per buy or sell on the weight traded.  ",
         "**Returns are raw.** *vs S&P 500* = annual return minus the S&P 500's (Newey-West t, "
         f"{NW_LAGS} lags). *Buy every call* = same timing and weights, every call bought, no "
         "score: the fair yardstick for what the score adds.", ""]

    labels = [("ours", f"**Long-only, FinBERT top {lp} (net of costs)**"),
              ("ours_gross", f"Long-only, FinBERT top {lp}, before costs"),
              ("all_calls", "Buy every call, no score (net)"),
              ("nolang", f"Long-only, no-language score top {lp} (net)"),
              ("velu", f"Long-only, Velu's VADER score top {lp} (net)"),
              ("ours_20", "Long-only, FinBERT top 20% (net)"),
              ("two_to_one", "2:1 long-short, FinBERT 20%/20% (earlier run, net)"),
              ("neutral", "1:1 market-neutral, FinBERT 20%/20% (main result, net)"),
              ("sp500", "S&P 500 buy-and-hold")]
    labels = [(k, l) for k, l in labels if k in series]
    for per in ("holdout", "valid", "all"):
        yrs = PERIODS[per]
        L += [f"## {PERIOD_NAME[per]}", "", HEAD]
        spp = in_years(sp, yrs)
        for key, lab in labels:
            L.append(row(lab, in_years(series[key], yrs), spp))
        L.append("")

    sph = in_years(sp, PERIODS["holdout"])
    L += ["## What the score adds (holdout 2018–2025)", "",
          "Difference in annual return against *buy every call* (same universe, timing, weights and "
          "dividend treatment), Newey-West t on the daily differences.", "",
          "| Strategy | Return vs buy every call | t (p) |", "|---|---|---|"]
    base = in_years(series["all_calls"], PERIODS["holdout"])
    for key, lab in labels:
        if key in ("ours", "ours_gross", "nolang", "velu", "ours_20"):
            vm = vs_market(in_years(series[key], PERIODS["holdout"]), base)
            L.append(f"| {lab} | {pct(vm['excess'])} | {vm['t_ex']:.2f} ({vm['p_ex']:.3f})"
                     f"{stars(vm['p_ex'])} |")

    L += ["", "## Return beyond market exposure (holdout 2018–2025)", "",
          "*Alpha* = annual return − beta × S&P 500 return (Newey-West t on daily values).", "",
          "| Strategy | Beta | Alpha per year | t (p) |", "|---|---|---|---|"]
    for key, lab in labels:
        if key != "sp500":
            vm = vs_market(in_years(series[key], PERIODS["holdout"]), sph)
            L.append(f"| {lab} | {vm['beta']:.2f} | {pct(vm['alpha'])} | "
                     f"{vm['t_a']:.2f} ({vm['p_a']:.3f}){stars(vm['p_a'])} |")

    hd = day_ours.loc[in_years(series["ours"], PERIODS["holdout"]).index]
    L += ["", "## Costs (holdout 2018–2025)", "",
          "| Cost per buy or sell | Annual return | Sharpe | vs S&P 500 per year |", "|---|---|---|---|"]
    for c in COST_GRID:
        r = long_only(hd, c)
        mt, vm = metrics(r), vs_market(r, sph)
        L.append(f"| {c} bps | {pct(mt['ann_return'])} | {mt['sharpe']:.2f} | {pct(vm['excess'])} |")

    yr = pd.DataFrame({f"Long-only top {lp} (net)": by_year(series["ours"]),
                       "Buy every call (net)": by_year(series["all_calls"]),
                       "S&P 500": by_year(sp)})
    yr = yr.loc[(yr.index >= 2013) & (yr.index <= 2025)]
    end = series["ours"].index[-1]
    L += ["", "## Year by year", "", "| Year | " + " | ".join(yr.columns) + " |",
          "|---" * (len(yr.columns) + 1) + "|"]
    for y, r in yr.iterrows():
        lab = f"{y} (to {end:%d %b})" if y == end.year and end.month < 12 else str(y)
        L.append(f"| {lab} | " + " | ".join(pct(v) for v in r.values) + " |")

    no20 = in_years(series["ours"][series["ours"].index.year != 2020], PERIODS["holdout"])
    mt20 = metrics(no20)
    L += ["", "## Notes", "",
          f"- Holdout without 2020: {pct(mt20['ann_return'])} a year, Sharpe {mt20['sharpe']:.2f}.",
          f"- Average positions open (holdout): {hd['n_long'].mean():.0f}. Weight traded: "
          f"{hd['turn_long'].mean() * 252:.1f}× capital per year.",
          "- **Dividends:** stock prices are dividend-adjusted but the S&P 500 series is the price "
          "index, so *vs S&P 500* flatters the strategy by roughly the index's dividend yield "
          "(about 1.5–2% a year). *Buy every call* has the same treatment, so the score's "
          "contribution is measured fairly against it.",
          ("- The 20% cut-off comes from Phase 4." if abs(long_pct - 0.20) < 1e-9 else
           f"- **The {lp} cut-off was chosen after seeing the earlier runs**, so this is an "
           "exploratory variant, not a pre-set test like the main result."),
          "- Same caveats as the main backtest: survivorship bias, closing-price fills, no cost for "
          "daily rebalancing.",
          f"- Series end on {end.date()}, the last new trade; the S&P 500 is cut to the same dates.",
          "", f"Chart: [`{chart_png.name}`]({chart_png.name})."]
    out_md.write_text("\n".join(L) + "\n", encoding="utf-8")


def plot(series, long_pct, chart_png):
    ink, ink2, grid, surface = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
    lines = [("ours", f"Long-only, FinBERT top {long_pct:.0%} (net)", "#2a78d6", "-"),
             ("all_calls", "Buy every call, no score (net)", "#eda100", "-"),
             ("nolang", f"Long-only, no-language top {long_pct:.0%} (net)", "#eb6834", "-"),
             ("neutral", "1:1 market-neutral FinBERT (main result, net)", "#1baf7a", "-"),
             ("sp500", "S&P 500 buy-and-hold (no dividends)", ink2, "--")]
    fig, (ax, ax2) = plt.subplots(2, 1, figsize=(11, 7.5), sharex=True,
                                  gridspec_kw={"height_ratios": [3, 1.2], "hspace": 0.08})
    fig.patch.set_facecolor(surface)
    ends = []
    for key, lab, col, ls in lines:
        r = in_years(series[key], PERIODS["holdout"])
        w = 100 * (1 + r).cumprod()
        ax.plot(w.index, w.values, color=col, lw=2, ls=ls, label=lab)
        ends.append([w.iloc[-1], w.index[-1]])
    ends.sort(key=lambda e: e[0])
    ends[0].append(ends[0][0])
    for i in range(1, len(ends)):
        ends[i].append(max(ends[i][0], ends[i - 1][2] + 8))
    for val, when, ypos in ends:
        ax.annotate(f"{val:.0f}", (when, val), xytext=(when + pd.Timedelta(days=30), ypos),
                    textcoords="data", va="center", fontsize=9, color=ink)
    ax.axhline(100, color=ink2, lw=0.8)
    ax.set_ylabel("Value of 100 invested", color=ink)
    ax.set_title(f"Phase 5 variant, holdout 2018–2025: long-only, top {long_pct:.0%} of scores",
                 loc="left", fontsize=13, color=ink, pad=10)
    ax.legend(frameon=False, loc="upper left", fontsize=9, labelcolor=ink)
    for key, col, ls in (("ours", "#2a78d6", "-"), ("sp500", ink2, "--")):
        r = in_years(series[key], PERIODS["holdout"])
        w = (1 + r).cumprod()
        ax2.plot(w.index, 100 * (w / w.cummax() - 1), color=col, lw=1.3, ls=ls)
    ax2.set_ylabel("Drawdown (%)", color=ink)
    ax2.set_title(f"Fall from previous peak: long-only top {long_pct:.0%} (solid) vs S&P 500 "
                  "(dashed)", loc="left", fontsize=10, color=ink2)
    for a in (ax, ax2):
        a.set_facecolor(surface)
        a.grid(True, color=grid, lw=0.6)
        for s in ("top", "right"):
            a.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            a.spines[s].set_color(grid)
        a.tick_params(colors=ink2, labelsize=9)
    ax.margins(x=0.06)
    fig.savefig(chart_png, dpi=130, bbox_inches="tight", facecolor=surface)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--long-pct", type=float, default=0.15,
                    help="top fraction of scores to buy (default 0.15)")
    long_pct = ap.parse_args().long_pct
    tag = f"_l{long_pct * 100:.0f}"
    daily_csv = Path(f"data/backtest_finbert_longonly{tag}_daily.csv")
    out_md = Path(f"docxxs/Phase5_finbert_longonly{tag}_results.md")
    chart_png = Path(f"docxxs/phase5_equity_curve_longonly{tag}.png")

    print(f"[long-only] top {long_pct:.0%} ... loading")
    m = Market(load_prices())
    preds = pd.read_csv(PRED_CSV, parse_dates=["call_date"])
    preds = preds[~preds["ticker"].isin(BAD_PRICE_TICKERS)]

    days = {"ours": live_days(preds, "score_final", "ours", m, long_pct),
            "nolang": live_days(preds, "score_nolang", "nolang", m, long_pct),
            "all_calls": live_days(preds, "score_final", "all", m, 1.0)}
    if VELU_CSV.exists():
        velu = pd.read_csv(VELU_CSV, parse_dates=["call_date"])
        velu = velu[~velu["ticker"].isin(BAD_PRICE_TICKERS)]
        days["velu"] = live_days(velu, "score_reaction_lr", "velu", m, long_pct)
    series = {k: long_only(v) for k, v in days.items()}
    series["ours_gross"] = long_only(days["ours"], 0)

    d20 = live_days(preds, "score_final", "ours", m, 0.20, 0.20)    # earlier runs' picks
    if abs(long_pct - 0.20) > 1e-9:
        series["ours_20"] = long_only(d20)
    series["two_to_one"] = two_to_one(d20)    # 100 long / 50 short, as in backtest_finbert_2to1
    series["neutral"] = net_returns(d20)      # the main 1:1 result
    sp = pd.Series(m.mkt_ret, index=m.dates)
    series["sp500"] = sp.loc[series["ours"].index]

    pd.DataFrame(series).loc[lambda x: x.index.year >= 2012].to_csv(daily_csv, index_label="date")
    for per in ("holdout", "valid"):
        r = in_years(series["ours"], PERIODS[per])
        mt, vm = metrics(r), vs_market(r, in_years(series["sp500"], PERIODS[per]))
        print(f"[long-only] {PERIOD_NAME[per]}: annual {pct(mt['ann_return'])}, "
              f"Sharpe {mt['sharpe']:.2f}, max DD {pct(mt['max_dd'])}, beta {vm['beta']:.2f}, "
              f"vs S&P {pct(vm['excess'])}")
    write_results(series, days["ours"], long_pct, out_md, chart_png)
    plot(series, long_pct, chart_png)
    print(f"[long-only] results -> {out_md}, chart -> {chart_png}, daily -> {daily_csv}")


if __name__ == "__main__":
    main()
