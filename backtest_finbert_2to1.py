"""
Phase 5 variant — 2:1 long-short on the FinBERT score
======================================================
Same stock picks and timing as backtest_finbert.py (the main, market-neutral result, which this
script does not change):

  SIGNAL   top 20% of the past 365 days' scores -> LONG, bottom 20% -> SHORT
  TIMING   enter at the close of day +2, exit at the close of day +60

Only the sizing differs. Per 100 of capital: 100 long (equal weight across the open longs) and
50 short (equal weight across the open shorts). The strategy is therefore net 50% long and moves
partly with the market, so results are RAW returns, compared with holding the S&P 500.

    R_day = 1.0 x mean(long returns) - 0.5 x mean(short returns) - costs
    costs = 10 bps x (1.0 x long weight traded + 0.5 x short weight traded)
            + 0.5%/year borrow fee on the 50 short

If a leg has no open positions, the S&P 500 stands in for it (as in the main script).

Caveat: stock prices are dividend-adjusted, but ^GSPC is the price index without dividends, so
the comparison flatters the strategy by roughly the S&P 500's dividend yield.

Reads:  data/predictions_finbert.csv, data/prices.csv
Writes: data/backtest_finbert_2to1_daily.csv
        docxxs/Phase5_finbert_2to1_results.md
        docxxs/phase5_equity_curve_2to1.png

Usage:
    python backtest_finbert_2to1.py
"""

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from backtest_finbert import (BAD_PRICE_TICKERS, BORROW, COST_BPS, COST_GRID, DAYS_PER_YEAR,
                              NW_LAGS, PERIOD_NAME, PERIODS, PRED_CSV, Market,
                              assign_sides, build_trades, by_year, daily_portfolio, in_years,
                              metrics, net_returns, pct, stars)
from phase1_abnormal_returns import load_prices
from phase4_market_reaction_test import newey_west

W_LONG, W_SHORT = 1.0, 0.5
LONG_PCT = 0.20                 # top fraction bought
SHORT_PCT = 0.20                # bottom fraction shorted (--short-pct changes it)
DAILY_CSV  = Path("data/backtest_finbert_2to1_daily.csv")
RESULTS_MD = Path("docxxs/Phase5_finbert_2to1_results.md")
CHART_PNG  = Path("docxxs/phase5_equity_curve_2to1.png")


def is_default():
    return abs(LONG_PCT - 0.20) < 1e-9 and abs(SHORT_PCT - 0.20) < 1e-9


def set_config(long_pct, short_pct):
    """Use other cut-offs; outputs get their own file names (e.g. _l20s10, _l15s15)."""
    global LONG_PCT, SHORT_PCT, DAILY_CSV, RESULTS_MD, CHART_PNG
    LONG_PCT, SHORT_PCT = long_pct, short_pct
    if not is_default():
        tag = f"_l{LONG_PCT * 100:.0f}s{SHORT_PCT * 100:.0f}"
        DAILY_CSV  = Path(f"data/backtest_finbert_2to1{tag}_daily.csv")
        RESULTS_MD = Path(f"docxxs/Phase5_finbert_2to1{tag}_results.md")
        CHART_PNG  = Path(f"docxxs/phase5_equity_curve_2to1{tag}.png")


def picks():
    return f"top {LONG_PCT:.0%} long / bottom {SHORT_PCT:.0%} short"


def two_to_one(day, cost_bps=COST_BPS):
    """Raw daily return of 100 long / 50 short, after costs."""
    cost = cost_bps / 1e4 * (W_LONG * day["turn_long"] + W_SHORT * day["turn_short"])
    borrow = BORROW / DAYS_PER_YEAR * W_SHORT * (day["n_short"] > 0)
    return W_LONG * day["long_ret"] - W_SHORT * day["short_ret"] - cost - borrow


def vs_market(r, sp):
    """Beta, correlation and the annual return above the S&P 500 (with Newey-West t)."""
    x = pd.concat([r, sp], axis=1, keys=["r", "sp"]).dropna()
    beta = np.cov(x["r"], x["sp"])[0, 1] / x["sp"].var()
    mean, t, p, _ = newey_west((x["r"] - x["sp"]).values, NW_LAGS)
    a_mean, a_t, a_p, _ = newey_west((x["r"] - beta * x["sp"]).values, NW_LAGS)
    return {"beta": beta, "corr": x["r"].corr(x["sp"]), "excess": mean * DAYS_PER_YEAR,
            "t_ex": t, "p_ex": p, "alpha": a_mean * DAYS_PER_YEAR, "t_a": a_t, "p_a": a_p}


HEAD = ("| Strategy | Annual return | Volatility | Sharpe | Max drawdown | Beta | "
        "vs S&P 500 per year (t, p) |\n|---|---|---|---|---|---|---|")


def row(label, r, sp):
    mt, vm = metrics(r), vs_market(r, sp)
    vs = ("—" if r.equals(sp) else
          f"{pct(vm['excess'])} ({vm['t_ex']:.2f}, {vm['p_ex']:.3f}){stars(vm['p_ex'])}")
    return (f"| {label} | {pct(mt['ann_return'])} | {mt['vol'] * 100:.1f}% | {mt['sharpe']:.2f} | "
            f"{pct(mt['max_dd'])} | {vm['beta']:.2f} | {vs} |")


def write_results(series, day_ours):
    sp = series["sp500"]
    L = [f"# Phase 5 variant — 2:1 Long-Short (100 long / 50 short), {picks()}", "",
         "Generated by [`backtest_finbert_2to1.py`](../backtest_finbert_2to1.py)"
         + (f" `--long-pct {LONG_PCT:g}`" if abs(LONG_PCT - 0.20) > 1e-9 else "")
         + (f" `--short-pct {SHORT_PCT:g}`" if abs(SHORT_PCT - 0.20) > 1e-9 else "")
         + ". The main market-neutral result is unchanged: "
         "[`Phase5_finbert_results.md`](Phase5_finbert_results.md).", "",
         f"**Picks:** at each call, LONG if its score is in the top {LONG_PCT:.0%} of the previous "
         f"365 days' scores, SHORT if in the bottom {SHORT_PCT:.0%}; enter at day +2's close, exit "
         "at day +60's.  ",
         f"**Sizing:** per 100 of capital, {W_LONG * 100:.0f} long and {W_SHORT * 100:.0f} short "
         "(equal weight within each side), so the strategy is net 50% long.  ",
         f"**Costs:** {COST_BPS} bps per buy or sell on the weight traded; {BORROW:.1%} a year to "
         "borrow the 50 short.  ",
         "**Returns are raw** (they include the market's moves). *vs S&P 500* = the strategy's "
         "annual return minus the S&P 500's, with a Newey-West t-test "
         f"({NW_LAGS} lags) on the daily differences.", ""]

    labels = [("ours", f"**2:1, FinBERT score, {picks()} (net of costs)**"),
              ("ours_gross", "2:1, FinBERT score, before costs"),
              ("nolang", "2:1, no-language score (net)"),
              ("ours_2020", "2:1, FinBERT, top 20% / bottom 20% (earlier run, net)"),
              ("ours_2010", "2:1, FinBERT, top 20% / bottom 10% (earlier run, net)"),
              ("longonly", f"Long-only, FinBERT top {LONG_PCT:.0%} (same longs, no short, net)"),
              ("all_calls", "Long-only, buy every call, no score (net)"),
              ("neutral", "1:1 market-neutral, FinBERT 20%/20% (main result, net)"),
              ("sp500", "S&P 500 buy-and-hold")]
    for per in ("holdout", "valid", "all"):
        yrs = PERIODS[per]
        L += [f"## {PERIOD_NAME[per]}", "", HEAD]
        spp = in_years(sp, yrs)
        for key, lab in labels:
            if key in series:
                L.append(row(lab, in_years(series[key], yrs), spp))
        L.append("")

    hd = day_ours.loc[in_years(series["ours"], PERIODS["holdout"]).index]
    sph = in_years(sp, PERIODS["holdout"])
    L += ["## Costs (holdout 2018–2025)", "",
          "| Cost per buy or sell | Annual return | Sharpe | vs S&P 500 per year |", "|---|---|---|---|"]
    for c in COST_GRID:
        r = two_to_one(hd, c)
        mt, vm = metrics(r), vs_market(r, sph)
        L.append(f"| {c} bps | {pct(mt['ann_return'])} | {mt['sharpe']:.2f} | {pct(vm['excess'])} |")
    L.append("")

    yr = pd.DataFrame({f"2:1 FinBERT {LONG_PCT:.0%}/{SHORT_PCT:.0%} (net)": by_year(series["ours"])})
    if "ours_2020" in series:
        yr["2:1 FinBERT 20%/20% (net)"] = by_year(series["ours_2020"])
    if "longonly" in series:
        yr[f"Long-only top {LONG_PCT:.0%} (net)"] = by_year(series["longonly"])
    yr["1:1 market-neutral (net)"] = by_year(series["neutral"])
    yr["S&P 500"] = by_year(sp)
    yr = yr.loc[(yr.index >= 2013) & (yr.index <= 2025)]
    end = series["ours"].index[-1]
    L += ["## Year by year", "", "| Year | " + " | ".join(yr.columns) + " |",
          "|---" * (len(yr.columns) + 1) + "|"]
    for y, r in yr.iterrows():
        lab = f"{y} (to {end:%d %b})" if y == end.year and end.month < 12 else str(y)
        L.append(f"| {lab} | " + " | ".join(pct(v) for v in r.values) + " |")

    no20 = series["ours"][series["ours"].index.year != 2020]
    h20 = in_years(no20, PERIODS["holdout"])
    mt20, vm20 = metrics(h20), vs_market(h20, in_years(sp[sp.index.year != 2020], PERIODS["holdout"]))
    L += ["", "## Return beyond market exposure (holdout 2018–2025)", "",
          "The 2:1 strategy carries only about half the S&P 500's market risk, so matching the "
          "S&P's return is not the fair bar. *Alpha* = annual return − beta × S&P 500 return "
          "(Newey-West t on daily values).", "",
          "| Strategy | Beta | Alpha per year | t (p) |", "|---|---|---|---|"]
    for key, lab in labels:
        if key in series and key != "sp500":
            r = in_years(series[key], PERIODS["holdout"])
            vm = vs_market(r, sph)
            L.append(f"| {lab} | {vm['beta']:.2f} | {pct(vm['alpha'])} | "
                     f"{vm['t_a']:.2f} ({vm['p_a']:.3f}){stars(vm['p_a'])} |")
    L += ["", "## Notes", "",
          f"- Holdout without 2020: {pct(mt20['ann_return'])} a year, Sharpe {mt20['sharpe']:.2f}, "
          f"vs S&P 500 {pct(vm20['excess'])} a year (p {vm20['p_ex']:.3f}).",
          "- **Dividends:** stock prices are dividend-adjusted but the S&P 500 series is the price "
          "index, so *vs S&P 500* flatters the strategy by roughly the index's dividend yield "
          "(about 1.5–2% a year over this period).",
          f"- Average positions open (holdout): {hd['n_long'].mean():.0f} long, "
          f"{hd['n_short'].mean():.0f} short.",
          "- Same caveats as the main backtest: survivorship bias, closing-price fills, no cost for "
          "daily rebalancing.",
          ("- The 20% cut-offs and the day +2 → +60 hold come from Phase 4; nothing was tuned on "
           "this backtest." if abs(SHORT_PCT - 0.20) < 1e-9 else
           f"- **The {LONG_PCT:.0%} long / {SHORT_PCT:.0%} short cut-offs were chosen after seeing "
           "earlier results**, so this run is an exploratory variant, not a pre-set test like the "
           "main result."),
          f"- Series end on {end.date()}, the last new trade under these picks; the S&P 500 is cut "
          "to the same dates.",
          "", f"Chart: [`{CHART_PNG.name}`]({CHART_PNG.name})."]
    RESULTS_MD.write_text("\n".join(L) + "\n", encoding="utf-8")


def plot(series):
    ink, ink2, grid, surface = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
    lines = [("ours", f"2:1 FinBERT, {picks()} (net)", "#2a78d6", "-"),
             ("ours_2020", "2:1 FinBERT, top 20% / bottom 20% (net)", "#6250d6", "-"),
             ("longonly", f"Long-only FinBERT top {LONG_PCT:.0%} (net)", "#eda100", "-"),
             ("neutral", "1:1 market-neutral FinBERT (main result, net)", "#1baf7a", "-"),
             ("nolang", "2:1 no-language score (net)", "#eb6834", "-"),
             ("sp500", "S&P 500 buy-and-hold (no dividends)", ink2, "--")]
    lines = [l for l in lines if l[0] in series]
    fig, (ax, ax2) = plt.subplots(2, 1, figsize=(11, 7.5), sharex=True,
                                  gridspec_kw={"height_ratios": [3, 1.2], "hspace": 0.08})
    fig.patch.set_facecolor(surface)
    ends = []
    for key, lab, col, ls in lines:
        r = in_years(series[key], PERIODS["holdout"])
        w = 100 * (1 + r).cumprod()
        ax.plot(w.index, w.values, color=col, lw=2, ls=ls, label=lab)
        ends.append([w.iloc[-1], w.index[-1]])
    ends.sort(key=lambda e: e[0])
    ends[0].append(ends[0][0])
    for i in range(1, len(ends)):
        ends[i].append(max(ends[i][0], ends[i - 1][2] + 7))
    for val, when, ypos in ends:
        ax.annotate(f"{val:.0f}", (when, val), xytext=(when + pd.Timedelta(days=30), ypos),
                    textcoords="data", va="center", fontsize=9, color=ink)
    ax.axhline(100, color=ink2, lw=0.8)
    ax.set_ylabel("Value of 100 invested", color=ink)
    ax.set_title(f"Phase 5 variant, holdout 2018–2025: 100 long / 50 short ({picks()})",
                 loc="left", fontsize=13, color=ink, pad=10)
    ax.legend(frameon=False, loc="upper left", fontsize=9, labelcolor=ink)
    for key, col in (("ours", "#2a78d6"), ("sp500", ink2)):
        r = in_years(series[key], PERIODS["holdout"])
        w = (1 + r).cumprod()
        dd = 100 * (w / w.cummax() - 1)
        ax2.plot(dd.index, dd.values, color=col, lw=1.3, ls="-" if key == "ours" else "--")
    ax2.set_ylabel("Drawdown (%)", color=ink)
    ax2.set_title("Fall from previous peak: 2:1 FinBERT (solid) vs S&P 500 (dashed)", loc="left",
                  fontsize=10, color=ink2)
    for a in (ax, ax2):
        a.set_facecolor(surface)
        a.grid(True, color=grid, lw=0.6)
        for s in ("top", "right"):
            a.spines[s].set_visible(False)
        for s in ("left", "bottom"):
            a.spines[s].set_color(grid)
        a.tick_params(colors=ink2, labelsize=9)
    ax.margins(x=0.06)
    fig.savefig(CHART_PNG, dpi=130, bbox_inches="tight", facecolor=surface)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--long-pct", type=float, default=0.20,
                    help="top fraction of scores to buy (default 0.20)")
    ap.add_argument("--short-pct", type=float, default=0.20,
                    help="bottom fraction of scores to short (default 0.20)")
    args = ap.parse_args()
    set_config(args.long_pct, args.short_pct)
    print(f"[2:1] {picks()} ... loading")
    m = Market(load_prices())
    preds = pd.read_csv(PRED_CSV, parse_dates=["call_date"])
    preds = preds[~preds["ticker"].isin(BAD_PRICE_TICKERS)]
    sources = {"ours": (preds, "score_final"), "nolang": (preds, "score_nolang")}

    def live_days(calls, col, name, bottom, top=None):
        top = LONG_PCT if top is None else top
        trades, paths = build_trades(assign_sides(calls, col, top, bottom), m, name)
        day = daily_portfolio(paths, m)
        held = (day["n_long"] + day["n_short"]) > 0
        live = (day.index >= held.idxmax()) & (day.index <= pd.Timestamp(trades["entry_date"].max()))
        return day[live]

    days, series = {}, {}
    for name, (calls, col) in sources.items():
        days[name] = live_days(calls, col, name, SHORT_PCT)
        series[name] = two_to_one(days[name])
    series["ours_gross"] = two_to_one(days["ours"], 0) + BORROW / DAYS_PER_YEAR * W_SHORT * (
        days["ours"]["n_short"] > 0)
    # the main 1:1 result (20%/20% picks), and the earlier 2:1 20%/20% run, for comparison
    day_2020 = days["ours"] if is_default() else live_days(preds, "score_final", "ours", 0.20, 0.20)
    series["neutral"] = net_returns(day_2020)
    if not is_default():
        series["ours_2020"] = two_to_one(day_2020)
    if abs(LONG_PCT - 0.20) > 1e-9:
        # extra comparisons for runs with a different long cut-off (e.g. 15%/15%)
        series["ours_2010"] = two_to_one(live_days(preds, "score_final", "ours", 0.10, 0.20))
        series["longonly"] = (days["ours"]["long_ret"]
                              - COST_BPS / 1e4 * days["ours"]["turn_long"])   # same longs, no short
        all_calls = live_days(preds, "score_final", "all", 0.0, 1.0)
        series["all_calls"] = all_calls["long_ret"] - COST_BPS / 1e4 * all_calls["turn_long"]
    sp = pd.Series(m.mkt_ret, index=m.dates)
    series["sp500"] = sp.loc[series["ours"].index]

    out = pd.DataFrame({k: v for k, v in series.items()})
    out[out.index.year >= 2012].to_csv(DAILY_CSV, index_label="date")
    for per in ("holdout", "valid"):
        r = in_years(series["ours"], PERIODS[per])
        mt, vm = metrics(r), vs_market(r, in_years(series["sp500"], PERIODS[per]))
        print(f"[2:1] {PERIOD_NAME[per]}: annual {pct(mt['ann_return'])}, Sharpe {mt['sharpe']:.2f}, "
              f"max DD {pct(mt['max_dd'])}, beta {vm['beta']:.2f}, vs S&P {pct(vm['excess'])}")
    write_results(series, days["ours"])
    plot(series)
    print(f"[2:1] results -> {RESULTS_MD}, chart -> {CHART_PNG}, daily -> {DAILY_CSV}")


if __name__ == "__main__":
    main()
